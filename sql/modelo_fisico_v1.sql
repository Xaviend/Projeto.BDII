-- BLOCO 2 - CIDADE, CAMPUS E FERIADO

CREATE TABLE tb_cidade (
    id_cidade  INT          GENERATED BY DEFAULT AS IDENTITY,
    nm_cidade  VARCHAR(60)  NOT NULL,
    sg_uf      CHAR(2)      NOT NULL,                       -- sempre 2 letras: CHAR e não VARCHAR

    CONSTRAINT pk_cidade        PRIMARY KEY (id_cidade),
    CONSTRAINT uq_cidade_nm_uf  UNIQUE (nm_cidade, sg_uf),  -- pode haver cidades com o mesmo nome em UFs diferentes
    CONSTRAINT ck_cidade_sg_uf  CHECK (sg_uf ~ '^[A-Z]{2}$'),-- 2 letras maiúsculas
    CONSTRAINT ck_cidade_nm     CHECK (btrim(nm_cidade) <> '') -- NOT NULL não barra '' nem '   '
);

-- tb_cidade (1,1) ---- (0,N) tb_campus
CREATE TABLE tb_campus (
    id_campus  INT          GENERATED BY DEFAULT AS IDENTITY,
    nm_campus  VARCHAR(60)  NOT NULL,
    id_cidade  INT          NOT NULL,                       -- NOT NULL = lado (1,1): todo campus fica em uma cidade

    CONSTRAINT pk_campus         PRIMARY KEY (id_campus),
    CONSTRAINT uq_campus_nm      UNIQUE (nm_campus),
    CONSTRAINT ck_campus_nm      CHECK (btrim(nm_campus) <> ''),
    CONSTRAINT fk_campus_cidade  FOREIGN KEY (id_cidade) REFERENCES tb_cidade (id_cidade)  -- tb_cidade (1,1) ---- (0,N) tb_campus
);

-- tb_campus (0,1) ---- (0,N) tb_feriado
CREATE TABLE tb_feriado (
    id_feriado  INT           GENERATED BY DEFAULT AS IDENTITY,
    dt_feriado  DATE          NOT NULL,
    ds_feriado  VARCHAR(120)  NOT NULL,
    id_campus   INT,                                        -- aceita NULL = lado (0,1): NULL é feriado nacional

    CONSTRAINT pk_feriado            PRIMARY KEY (id_feriado),
    -- NULLS NOT DISTINCT: dois NULL contam como iguais, então não deixa 2 feriados nacionais no mesmo dia
    CONSTRAINT uq_feriado_dt_campus  UNIQUE NULLS NOT DISTINCT (dt_feriado, id_campus),
    CONSTRAINT fk_feriado_campus     FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)  -- tb_campus (0,1) ---- (0,N) tb_feriado
);


