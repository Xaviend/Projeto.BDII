--BLOCO 1 - SCHEMA, EXTENSÃO, DOMÍNIOS E TIPOS

-- Apaga e recria: Com isso o script pode rodar várias vezes sem erro
DROP SCHEMA IF EXISTS projeto_bd2 CASCADE;
CREATE SCHEMA projeto_bd2;
SET search_path TO projeto_bd2, public;

-- btree_gist deixa usar "=" junto com "&&" (sobreposição) em um EXCLUDE (ver tb_turma_horario)
-- fica no public: assim não é apagada e recriada junto com o schema a cada execução
CREATE EXTENSION IF NOT EXISTS btree_gist SCHEMA public;

-- DOMÍNIO = tipo base + regra. A regra vale em toda coluna que usar o domínio, sem repetir o CHECK.
CREATE DOMAIN dm_nota AS NUMERIC(4,2)          -- 2 casas decimais, até 99,99
    CHECK (VALUE >= 0 AND VALUE <= 10);        -- mas nota só vai de 0 a 10

CREATE DOMAIN dm_percentual AS NUMERIC(5,2)    -- até 999,99
    CHECK (VALUE >= 0 AND VALUE <= 100);       -- mas percentual só vai de 0 a 100

-- ENUM = lista fechada de valores. Valor fora da lista é recusado.
CREATE TYPE tp_grau             AS ENUM ('bacharelado', 'licenciatura', 'tecnologo');
CREATE TYPE tp_titulacao        AS ENUM ('especialista', 'mestre', 'doutor');
CREATE TYPE tp_tipo_sala        AS ENUM ('teorica', 'laboratorio', 'auditorio');
CREATE TYPE tp_turno            AS ENUM ('matutino', 'vespertino', 'noturno');
CREATE TYPE tp_vinculo          AS ENUM ('pre_requisito', 'co_requisito');
CREATE TYPE tp_tipo_disciplina  AS ENUM ('obrigatoria', 'optativa', 'eletiva');
CREATE TYPE tp_status_matricula AS ENUM ('ativa', 'trancada', 'cancelada', 'concluida');
CREATE TYPE tp_situacao         AS ENUM ('cursando', 'aprovado', 'reprovado_nota', 'reprovado_falta');

