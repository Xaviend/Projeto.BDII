--BLOCO 4 - CURRÍCULO x DISCIPLINA E PRÉ-REQUISITO (N:N)

-- Associativa do N:N:  tb_curriculo (1,1) ---- (0,N) tb_curriculo_disciplina (0,N) ---- (1,1) tb_disciplina
CREATE TABLE tb_curriculo_disciplina (
    id_curriculo_disciplina  INT                 GENERATED BY DEFAULT AS IDENTITY,
    id_curriculo             INT                 NOT NULL,  -- (1,1)
    id_disciplina            INT                 NOT NULL,  -- (1,1)
    cd_periodo_grade         SMALLINT            NOT NULL,  -- em qual semestre da grade fica (1º, 2º...): posição, por isso cd_ e não qt_
    ds_tipo                  tp_tipo_disciplina  NOT NULL DEFAULT 'obrigatoria',

    CONSTRAINT pk_curriculo_disciplina  PRIMARY KEY (id_curriculo_disciplina),
    CONSTRAINT uq_cd_curriculo_disc     UNIQUE (id_curriculo, id_disciplina), -- a mesma disciplina não entra 2x na grade
    CONSTRAINT ck_cd_periodo_grade      CHECK (cd_periodo_grade BETWEEN 1 AND 12),
    CONSTRAINT fk_cd_curriculo          FOREIGN KEY (id_curriculo)  REFERENCES tb_curriculo (id_curriculo)
                                        ON DELETE CASCADE,       -- tb_curriculo (1,1) ---- (0,N); apagou a grade, apaga os itens
    CONSTRAINT fk_cd_disciplina         FOREIGN KEY (id_disciplina) REFERENCES tb_disciplina (id_disciplina)  -- tb_disciplina (1,1) ---- (0,N)
);

-- Auto-relacionamento N:N em tb_disciplina: "id_disciplina EXIGE id_disciplina_requisito"
-- tb_disciplina (1,1) ---- (0,N) tb_pre_requisito  (duas vezes: uma pela disciplina, outra pelo requisito)
CREATE TABLE tb_pre_requisito (
    id_pre_requisito         INT         GENERATED BY DEFAULT AS IDENTITY,
    id_disciplina            INT         NOT NULL,          -- a disciplina que tem a exigência
    -- EXCEÇÃO CONSCIENTE à regra "FK com o mesmo nome da PK": num auto-relacionamento as duas FKs apontam
    -- para tb_disciplina.id_disciplina, e duas colunas não podem ter o mesmo nome na mesma tabela.
    -- Mantém o id_ (é chave) + um sufixo que diz o papel da coluna.
    id_disciplina_requisito  INT         NOT NULL,          -- a disciplina exigida
    ds_vinculo               tp_vinculo  NOT NULL DEFAULT 'pre_requisito',

    CONSTRAINT pk_pre_requisito     PRIMARY KEY (id_pre_requisito),
    CONSTRAINT uq_pre_req_par       UNIQUE (id_disciplina, id_disciplina_requisito),
    CONSTRAINT ck_pre_req_si_mesma  CHECK (id_disciplina <> id_disciplina_requisito),
    CONSTRAINT fk_pre_req_disc      FOREIGN KEY (id_disciplina)           REFERENCES tb_disciplina (id_disciplina)
                                    ON DELETE CASCADE,          -- tb_disciplina (1,1) ---- (0,N), papel "disciplina"
    CONSTRAINT fk_pre_req_requisito FOREIGN KEY (id_disciplina_requisito) REFERENCES tb_disciplina (id_disciplina)  -- (1,1) ---- (0,N), papel "requisito"
);


