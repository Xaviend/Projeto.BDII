-- BLOCO 3 - CURSO, CURRÍCULO E DISCIPLINA

-- tb_campus (1,1) ---- (0,N) tb_curso
CREATE TABLE tb_curso (
    id_curso     INT           GENERATED BY DEFAULT AS IDENTITY,
    cd_curso     VARCHAR(10)   NOT NULL,
    nm_curso     VARCHAR(120)  NOT NULL,
    ds_grau      tp_grau       NOT NULL,
    qt_ch_total  INT           NOT NULL,                    -- carga horária total, em horas
    id_campus    INT           NOT NULL,                    -- (1,1): todo curso pertence a um campus

    CONSTRAINT pk_curso         PRIMARY KEY (id_curso),
    CONSTRAINT uq_curso_cd      UNIQUE (cd_curso),
    CONSTRAINT ck_curso_ch      CHECK (qt_ch_total > 0),
    CONSTRAINT ck_curso_texto   CHECK (btrim(cd_curso) <> '' AND btrim(nm_curso) <> ''),
    CONSTRAINT fk_curso_campus  FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)  -- tb_campus (1,1) ---- (0,N) tb_curso
);

-- tb_curso (1,1) ---- (0,N) tb_curriculo
CREATE TABLE tb_curriculo (
    id_curriculo  INT       GENERATED BY DEFAULT AS IDENTITY,
    id_curso      INT       NOT NULL,                       -- (1,1): todo currículo é de um curso
    aa_vigencia   SMALLINT  NOT NULL,                       -- ano em que a grade começou a valer
    ic_ativo      BOOLEAN   NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_curriculo           PRIMARY KEY (id_curriculo),
    CONSTRAINT uq_curriculo_curso_aa  UNIQUE (id_curso, aa_vigencia), -- uma grade por curso por ano
    CONSTRAINT uq_curriculo_id_curso  UNIQUE (id_curriculo, id_curso),-- alvo da FK composta de tb_aluno
    CONSTRAINT ck_curriculo_aa        CHECK (aa_vigencia BETWEEN 1990 AND 2100),
    CONSTRAINT fk_curriculo_curso     FOREIGN KEY (id_curso) REFERENCES tb_curso (id_curso)  -- tb_curso (1,1) ---- (0,N) tb_curriculo
);

CREATE TABLE tb_disciplina (
    id_disciplina  INT            GENERATED BY DEFAULT AS IDENTITY,
    cd_disciplina  VARCHAR(10)    NOT NULL,
    nm_disciplina  VARCHAR(120)   NOT NULL,
    qt_ch_teorica  SMALLINT       NOT NULL DEFAULT 0,
    qt_ch_pratica  SMALLINT       NOT NULL DEFAULT 0,
    -- coluna GERADA: o banco calcula sozinho, ninguém consegue gravar um total errado
    qt_ch_total    SMALLINT       GENERATED ALWAYS AS (qt_ch_teorica + qt_ch_pratica) STORED,
    ds_ementa      VARCHAR(4000),

    CONSTRAINT pk_disciplina     PRIMARY KEY (id_disciplina),
    CONSTRAINT uq_disciplina_cd  UNIQUE (cd_disciplina),
    -- ">= 0" faz o papel do "unsigned" do MySQL; e a disciplina precisa ter alguma carga horária
    CONSTRAINT ck_disciplina_ch  CHECK (qt_ch_teorica >= 0 AND qt_ch_pratica >= 0
                                        AND qt_ch_teorica + qt_ch_pratica > 0),
    CONSTRAINT ck_disciplina_texto CHECK (btrim(cd_disciplina) <> '' AND btrim(nm_disciplina) <> '')
);


