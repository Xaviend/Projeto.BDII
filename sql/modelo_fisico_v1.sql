--BLOCO 6 - TURMA E HORÁRIO DA TURMA

-- tb_disciplina     (1,1) ---- (0,N) tb_turma
-- tb_periodo_letivo (1,1) ---- (0,N) tb_turma
-- tb_professor      (1,1) ---- (0,N) tb_turma
CREATE TABLE tb_turma (
    id_turma           INT          GENERATED BY DEFAULT AS IDENTITY,
    cd_turma           VARCHAR(15)  NOT NULL,
    id_disciplina      INT          NOT NULL,               -- (1,1)
    id_periodo_letivo  INT          NOT NULL,               -- (1,1)
    id_professor       INT          NOT NULL,               -- (1,1)
    ds_turno           tp_turno     NOT NULL,
    qt_vagas           SMALLINT     NOT NULL,

    CONSTRAINT pk_turma            PRIMARY KEY (id_turma),
    -- turma "A" pode existir em várias disciplinas e em vários semestres; só não repete na mesma disciplina e semestre
    CONSTRAINT uq_turma_cd         UNIQUE (cd_turma, id_disciplina, id_periodo_letivo),
    CONSTRAINT uq_turma_id_periodo UNIQUE (id_turma, id_periodo_letivo),               -- alvo da FK composta de tb_turma_horario
    CONSTRAINT ck_turma_vagas      CHECK (qt_vagas > 0),
    CONSTRAINT ck_turma_cd         CHECK (btrim(cd_turma) <> ''),
    CONSTRAINT fk_turma_disciplina FOREIGN KEY (id_disciplina)     REFERENCES tb_disciplina (id_disciplina),           -- (1,1) ---- (0,N)
    CONSTRAINT fk_turma_periodo    FOREIGN KEY (id_periodo_letivo) REFERENCES tb_periodo_letivo (id_periodo_letivo),   -- (1,1) ---- (0,N)
    CONSTRAINT fk_turma_professor  FOREIGN KEY (id_professor)      REFERENCES tb_professor (id_professor)              -- (1,1) ---- (0,N)
);

-- tb_turma (1,1) ---- (0,N) tb_turma_horario (0,N) ---- (1,1) tb_sala
-- tb_periodo_letivo (1,1) ---- (0,N) tb_turma_horario
CREATE TABLE tb_turma_horario (
    id_turma_horario   INT       GENERATED BY DEFAULT AS IDENTITY,
    id_turma           INT       NOT NULL,                  -- (1,1)
    id_sala            INT       NOT NULL,                  -- (1,1)
    -- repetido de tb_turma DE PROPÓSITO: o EXCLUDE só enxerga colunas da própria tabela (não aceita subconsulta).
    -- A FK composta abaixo garante que ele é SEMPRE igual ao semestre da turma: não há como divergir.
    id_periodo_letivo  INT       NOT NULL,                  -- (1,1)
    dd_semana         SMALLINT  NOT NULL,                   -- dia da semana: 1 = segunda ... 7 = domingo
    hr_inicio         TIME      NOT NULL,
    hr_fim            TIME      NOT NULL,

    CONSTRAINT pk_turma_horario  PRIMARY KEY (id_turma_horario),
    CONSTRAINT ck_th_dd_semana   CHECK (dd_semana BETWEEN 1 AND 7),
    CONSTRAINT ck_th_horario     CHECK (hr_fim > hr_inicio),
    CONSTRAINT fk_th_turma       FOREIGN KEY (id_turma, id_periodo_letivo)
                                 REFERENCES tb_turma (id_turma, id_periodo_letivo)
                                 ON DELETE CASCADE,                     -- tb_turma (1,1) ---- (0,N)
    CONSTRAINT fk_th_periodo     FOREIGN KEY (id_periodo_letivo) REFERENCES tb_periodo_letivo (id_periodo_letivo), -- (1,1) ---- (0,N)
    CONSTRAINT fk_th_sala        FOREIGN KEY (id_sala)  REFERENCES tb_sala (id_sala),                          -- tb_sala (1,1) ---- (0,N)
    -- Choque de sala: mesmo SEMESTRE (=), mesma sala (=), mesmo dia (=) e horários que se sobrepõem (&&) é proibido.
    -- Sem o semestre, a sala usada segunda 19h em 2026/1 ficaria bloqueada nesse horário para sempre.
    -- Como não usamos TIMERANGE, o intervalo é montado aqui dentro: data fixa + hora vira timestamp.
    CONSTRAINT ex_th_choque_sala EXCLUDE USING gist (
        id_periodo_letivo WITH =,
        id_sala           WITH =,
        dd_semana         WITH =,
        tsrange(DATE '2000-01-01' + hr_inicio, DATE '2000-01-01' + hr_fim) WITH &&
    )
);


