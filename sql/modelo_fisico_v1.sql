--BLOCO 5 - PROFESSOR, PERÍODO LETIVO E SALA

CREATE TABLE tb_professor (
    id_professor  INT           GENERATED BY DEFAULT AS IDENTITY,
    cd_matricula  VARCHAR(12)   NOT NULL,                   -- matrícula funcional
    nm_professor  VARCHAR(120)  NOT NULL,
    ds_email      VARCHAR(120)  NOT NULL,
    ds_titulacao  tp_titulacao  NOT NULL,

    CONSTRAINT pk_professor           PRIMARY KEY (id_professor),
    CONSTRAINT uq_professor_matricula UNIQUE (cd_matricula),
    CONSTRAINT uq_professor_email     UNIQUE (ds_email),
    CONSTRAINT ck_professor_email     CHECK (ds_email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'), -- algo@algo.algo
    CONSTRAINT ck_professor_texto     CHECK (btrim(cd_matricula) <> '' AND btrim(nm_professor) <> '')
);

CREATE TABLE tb_periodo_letivo (
    id_periodo_letivo  INT       GENERATED BY DEFAULT AS IDENTITY,
    aa_periodo         SMALLINT  NOT NULL,
    cd_semestre        SMALLINT  NOT NULL,                  -- 1 ou 2: identifica o semestre (por isso cd_ e não qt_)
    dt_inicio          DATE      NOT NULL,
    dt_fim             DATE      NOT NULL,

    CONSTRAINT pk_periodo_letivo   PRIMARY KEY (id_periodo_letivo),
    CONSTRAINT uq_periodo_aa_sem   UNIQUE (aa_periodo, cd_semestre),
    CONSTRAINT ck_periodo_semestre CHECK (cd_semestre IN (1, 2)),
    CONSTRAINT ck_periodo_datas    CHECK (dt_fim > dt_inicio),
    -- o semestre começa no ano que ele diz ser (barra 2026 com datas de 1980)
    CONSTRAINT ck_periodo_ano      CHECK (EXTRACT(YEAR FROM dt_inicio) = aa_periodo)
);

-- tb_campus (1,1) ---- (0,N) tb_sala
CREATE TABLE tb_sala (
    id_sala        INT           GENERATED BY DEFAULT AS IDENTITY,
    id_campus      INT           NOT NULL,                  -- (1,1)
    cd_sala        VARCHAR(10)   NOT NULL,
    qt_capacidade  SMALLINT      NOT NULL,
    ds_tipo        tp_tipo_sala  NOT NULL DEFAULT 'teorica',

    CONSTRAINT pk_sala             PRIMARY KEY (id_sala),
    CONSTRAINT uq_sala_campus_cd   UNIQUE (id_campus, cd_sala), -- "A101" pode existir em campus diferentes
    CONSTRAINT ck_sala_capacidade  CHECK (qt_capacidade > 0),
    CONSTRAINT ck_sala_cd          CHECK (btrim(cd_sala) <> ''),
    CONSTRAINT fk_sala_campus      FOREIGN KEY (id_campus) REFERENCES tb_campus (id_campus)  -- tb_campus (1,1) ---- (0,N) tb_sala
);


