--BLOCO 7 - ALUNO, MATRÍCULA, HISTÓRICO E LOG

-- tb_curso     (1,1) ---- (0,N) tb_aluno
-- tb_curriculo (1,1) ---- (0,N) tb_aluno
CREATE TABLE tb_aluno (
    id_aluno       INT           GENERATED BY DEFAULT AS IDENTITY,
    cd_matricula   VARCHAR(12)   NOT NULL,                  -- RA do aluno
    nm_aluno       VARCHAR(120)  NOT NULL,
    cd_cpf         CHAR(11)      NOT NULL,                  -- só os 11 dígitos, sem ponto e traço
    ds_email       VARCHAR(120)  NOT NULL,
    dt_nascimento  DATE          NOT NULL,
    id_curso       INT           NOT NULL,                  -- (1,1)
    id_curriculo   INT           NOT NULL,                  -- (1,1)
    dt_ingresso    DATE          NOT NULL DEFAULT CURRENT_DATE,
    ic_ativo       BOOLEAN       NOT NULL DEFAULT TRUE,

    CONSTRAINT pk_aluno           PRIMARY KEY (id_aluno),
    CONSTRAINT uq_aluno_matricula UNIQUE (cd_matricula),
    CONSTRAINT uq_aluno_cpf       UNIQUE (cd_cpf),
    CONSTRAINT uq_aluno_email     UNIQUE (ds_email),
    CONSTRAINT ck_aluno_cpf       CHECK (cd_cpf ~ '^[0-9]{11}$'
                                         AND cd_cpf !~ '^(.)\1{10}$'),  -- 11 dígitos e não todos iguais (000..., 111...)
    CONSTRAINT ck_aluno_email     CHECK (ds_email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$'),
    -- regra adotada: ninguém ingressa com menos de 14 anos
    CONSTRAINT ck_aluno_datas     CHECK (dt_ingresso >= dt_nascimento + INTERVAL '14 years'),
    CONSTRAINT ck_aluno_texto     CHECK (btrim(cd_matricula) <> '' AND btrim(nm_aluno) <> ''),
    -- tb_curso (1,1) ---- (0,N) tb_aluno. A FK composta abaixo já garante o curso; esta fica para o relacionamento
    -- aparecer no diagrama e na engenharia reversa (Generate ERD), e porque consulta "alunos por curso" é direta.
    CONSTRAINT fk_aluno_curso     FOREIGN KEY (id_curso) REFERENCES tb_curso (id_curso),
    -- FK COMPOSTA: o par (currículo, curso) tem que existir junto em tb_curriculo.
    -- Assim o aluno de Computação não fica com o currículo de Direito.
    CONSTRAINT fk_aluno_curriculo FOREIGN KEY (id_curriculo, id_curso)
                                  REFERENCES tb_curriculo (id_curriculo, id_curso)  -- tb_curriculo (1,1) ---- (0,N)
);

-- tb_aluno (1,1) ---- (0,N) tb_matricula (0,N) ---- (1,1) tb_turma
CREATE TABLE tb_matricula (
    id_matricula  INT                  GENERATED BY DEFAULT AS IDENTITY,
    id_aluno      INT                  NOT NULL,            -- (1,1)
    id_turma      INT                  NOT NULL,            -- (1,1)
    dt_matricula  TIMESTAMP            NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ds_status     tp_status_matricula  NOT NULL DEFAULT 'ativa',

    CONSTRAINT pk_matricula             PRIMARY KEY (id_matricula),
    CONSTRAINT uq_matricula_aluno_turma UNIQUE (id_aluno, id_turma), -- não se matricula 2x na mesma turma
    CONSTRAINT fk_matricula_aluno       FOREIGN KEY (id_aluno) REFERENCES tb_aluno (id_aluno),  -- tb_aluno (1,1) ---- (0,N)
    CONSTRAINT fk_matricula_turma       FOREIGN KEY (id_turma) REFERENCES tb_turma (id_turma)   -- tb_turma (1,1) ---- (0,N)
);

-- tb_matricula (1,1) ---- (0,1) tb_historico
-- 1:1 opcional: FK NOT NULL (todo histórico é de uma matrícula) + UNIQUE (cada matrícula tem no máximo 1 histórico)
CREATE TABLE tb_historico (
    id_historico    INT            GENERATED BY DEFAULT AS IDENTITY,
    id_matricula    INT            NOT NULL,
    qt_nota_a1      dm_nota,                                -- notas usam o domínio: o 0 a 10 vem junto
    qt_nota_a2      dm_nota,
    qt_nota_p3      dm_nota,
    pc_frequencia   dm_percentual,
    ds_situacao     tp_situacao    NOT NULL DEFAULT 'cursando',
    -- Média IESB: 0,4 x A1 + 0,6 x A2. A P3 substitui a nota que for pior para o aluno.
    -- GREATEST pega o maior valor e IGNORA os NULL: sem P3, sobra só a média normal.
    -- Se o aluno faltou a uma prova (nota NULL), a P3 entra no lugar dela. Com só UMA nota lançada, a média fica
    -- NULL de propósito: ainda não existe média. E a situação 'aprovado' exige média (ver ck_historico_aprovado).
    qt_media_final  NUMERIC(4,2)   GENERATED ALWAYS AS (
                        ROUND(GREATEST(0.4 * qt_nota_a1 + 0.6 * qt_nota_a2,
                                       0.4 * qt_nota_p3 + 0.6 * qt_nota_a2,
                                       0.4 * qt_nota_a1 + 0.6 * qt_nota_p3), 2)
                    ) STORED,

    CONSTRAINT pk_historico           PRIMARY KEY (id_historico),
    CONSTRAINT uq_historico_matricula UNIQUE (id_matricula),        -- o "máx 1" do (0,1)
    -- A situação tem que bater com os números. Média mínima de aprovação do IESB: 5,0.
    -- Atenção ao NULL: CHECK com resultado NULL PASSA. Por isso cada regra exige IS NOT NULL antes de comparar.
    CONSTRAINT ck_historico_aprovado  CHECK (ds_situacao <> 'aprovado'
                                             OR (pc_frequencia IS NOT NULL AND pc_frequencia >= 75
                                                 AND qt_media_final IS NOT NULL AND qt_media_final >= 5)),
    CONSTRAINT ck_historico_rep_nota  CHECK (ds_situacao <> 'reprovado_nota'
                                             OR (qt_media_final IS NOT NULL AND qt_media_final < 5)),
    CONSTRAINT ck_historico_falta     CHECK (ds_situacao <> 'reprovado_falta'
                                             OR (pc_frequencia IS NOT NULL AND pc_frequencia < 75)),
    CONSTRAINT fk_historico_matricula FOREIGN KEY (id_matricula) REFERENCES tb_matricula (id_matricula)
                                      ON DELETE CASCADE                -- tb_matricula (1,1) ---- (0,1) tb_historico
);

-- Log de auditoria. SEM FK de propósito: se a matrícula for apagada, o registro premanece.
CREATE TABLE tb_log_matricula (
    id_log_matricula  INT           GENERATED BY DEFAULT AS IDENTITY,
    id_matricula      INT           NOT NULL,               -- mesmo nome da PK de tb_matricula, mas sem FK
    ds_acao           VARCHAR(20)   NOT NULL,
    dt_ocorrencia     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    nm_usuario        VARCHAR(63)   NOT NULL DEFAULT CURRENT_USER, -- 63 = tamanho máximo de nome no PostgreSQL
    ds_detalhe        JSONB,                                -- dados antes/depois em JSON (pode ganhar índice GIN)

    CONSTRAINT pk_log_matricula PRIMARY KEY (id_log_matricula),
    CONSTRAINT ck_log_acao      CHECK (ds_acao IN ('INSERT', 'UPDATE', 'DELETE'))
);

